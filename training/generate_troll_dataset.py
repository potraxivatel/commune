def generate_variations(examples):
    results = []
    for query, reply in examples:
        results.append((query, reply))
        results.append((query.upper(), reply))
        results.append((query.capitalize() + "!!!", reply))
        results.append(("Слышь, " + query.lower(), reply))
        results.append((query.lower() + " слышишь нет?", reply))
    return results

def main():
    out_path = Path(__file__).parent / "troll_dataset.jsonl"
    all_examples = generate_variations(RAW_EXAMPLES)

    records = []
    for user_input, reply in all_examples:
        item = {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_input},
                {"role": "assistant", "content": reply},
            ]
        }
        records.append(item)

    with open(out_path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"✅ Generated {len(records)} toxic troll samples in {out_path.name}")

if __name__ == "__main__":
    main()
